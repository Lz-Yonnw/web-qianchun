export type { SourceRow };

function isoDate(dayOffset: number) {
  return new Date(BASE_DATE + dayOffset * DAY_MS).toISOString().slice(0, 10);
}

function previousPeriod(start: string, end: string) {
  const startTime = Date.parse(`${start}T00:00:00Z`);
  const endTime = Date.parse(`${end}T00:00:00Z`);
  if (!Number.isFinite(startTime) || !Number.isFinite(endTime)) {
    return { start: "", end: "" };
  }
  const periodDays = Math.max(1, Math.round((endTime - startTime) / DAY_MS) + 1);
  const previousEnd = startTime - DAY_MS;
  const previousStart = previousEnd - (periodDays - 1) * DAY_MS;

  return {
    start: new Date(previousStart).toISOString().slice(0, 10),
    end: new Date(previousEnd).toISOString().slice(0, 10),
  };
}

function hash(value: string) {
  let result = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    result ^= value.charCodeAt(index);
    result = Math.imul(result, 16777619);
  }
  return result >>> 0;
}

function syntheticRow(accountId: string, date: string): SourceRow {
  const dayOffset = Math.round((Date.parse(`${date}T00:00:00Z`) - BASE_DATE) / DAY_MS);
  const seed = hash(`${accountId}-${date}-synthetic`);
  const latest = ACCOUNT_ROWS[accountId] ?? [];
  const average = (index: 1 | 2 | 3 | 4 | 5) => latest.length
    ? latest.reduce((sum, row) => sum + row[index], 0) / latest.length
    : 0;
  const dailyFactor = 0.82 + (seed % 3701) / 10_000;
  const spendCents = Math.max(1, Math.round((average(1) || 110_000) * dailyFactor));
  const impressions = Math.max(1, Math.round((average(2) || spendCents * 28) * (0.9 + ((seed >>> 5) % 2001) / 10_000)));
  const clicks = Math.max(1, Math.round((average(3) || impressions * 0.04) * (0.9 + ((seed >>> 11) % 2001) / 10_000)));
  const orders = Math.max(1, Math.round((average(4) || clicks * 0.01) * (0.88 + ((seed >>> 17) % 2401) / 10_000)));
  const gmvCents = Math.max(1, Math.round((average(5) || spendCents * 2) * (0.88 + ((seed >>> 21) % 2401) / 10_000)));
  return [dayOffset, spendCents, impressions, clicks, orders, gmvCents];
}

function rowsForRange(accountId: string, rows: readonly SourceRow[], start: string, end: string) {
  const startTime = Date.parse(`${start}T00:00:00Z`);
  const endTime = Date.parse(`${end}T00:00:00Z`);
  if (!Number.isFinite(startTime) || !Number.isFinite(endTime) || startTime > endTime) return [];
  const byDate = new Map(rows.map((row) => [isoDate(row[0]), row]));
  const result: SourceRow[] = [];
  for (let time = startTime; time <= endTime; time += DAY_MS) {
    const date = new Date(time).toISOString().slice(0, 10);
    result.push(byDate.get(date) ?? syntheticRow(accountId, date));
  }
  return result;
}

function categoryShares(accountId: string) {
  const profile = getAccountDeliveryProfile(accountId);
  return {
    chengfang: 0,
    standard: profile.type === "standard" ? 1 : 0,
    omni: profile.type === "omni" ? 1 : 0,
    brand: 0,
  };
}

function measuresForRow(accountId: string, row: SourceRow, metricKey: Metric["key"]): Measures {
  const [dayOffset, spendCents, impressions, clicks, orders, gmvCents] = row;
  const spend = spendCents / 100;
  const gmv = gmvCents / 100;
  const shares = categoryShares(accountId);
  const spendShare = metricKey === "total" ? 1 : shares[metricKey];

  const revenueFactors = { chengfang: 1.08, standard: 0.96, omni: 1.12, brand: 0.88 };
  const revenueTotal = (Object.keys(shares) as (keyof typeof shares)[])
    .reduce((sum, key) => sum + shares[key] * revenueFactors[key], 0);
  const revenueShare = metricKey === "total"
    ? 1
    : shares[metricKey] * revenueFactors[metricKey] / revenueTotal;

  const metricSpend = spend * spendShare;
  const metricGmv = gmv * revenueShare;
  const metricOrders = orders * revenueShare;
  const metricImpressions = impressions * spendShare;
  const metricClicks = clicks * spendShare;
  const seed = hash(`${accountId}-${dayOffset}-quality`);

  return {
    consume: metricSpend,
    roi: metricSpend ? metricGmv / metricSpend : 0,
    gmv: metricGmv,
    orders: metricOrders,
    settleRate: 0.92 + (seed % 601) / 10_000,
    refundRate: 0.012 + ((seed >>> 7) % 181) / 10_000,
    impr: metricImpressions,
    clicks: metricClicks,
    click: metricImpressions ? metricClicks / metricImpressions : 0,
    orders7: metricOrders,
    gmv7: metricGmv,
    payRoi: metricSpend ? metricGmv / metricSpend : 0,
  };
}

function summarize(values: Measures[]): Measures {
  const consume = values.reduce((sum, item) => sum + item.consume, 0);
  const gmv = values.reduce((sum, item) => sum + item.gmv, 0);
  const orders = values.reduce((sum, item) => sum + item.orders, 0);
  const impr = values.reduce((sum, item) => sum + item.impr, 0);
  const clicks = values.reduce((sum, item) => sum + item.clicks, 0);
  const settleWeight = gmv || 1;
  const refundWeight = orders || 1;

  return {
    consume,
    roi: consume ? gmv / consume : 0,
    gmv,
    orders,
    settleRate: values.reduce((sum, item) => sum + item.settleRate * item.gmv, 0) / settleWeight,
    refundRate: values.reduce((sum, item) => sum + item.refundRate * item.orders, 0) / refundWeight,
    impr,
    clicks,
    click: impr ? clicks / impr : 0,
    orders7: orders,
    gmv7: gmv,
    payRoi: consume ? gmv / consume : 0,
  };
}

function metricNumber(measures: Measures, key: string) {
  if (key === "cpm") return measures.impr ? measures.consume / measures.impr * 1_000 : 0;
  if (key === "cost") return measures.orders ? measures.consume / measures.orders : 0;
  return measures[key as keyof Measures] ?? 0;
}

function formatNumber(value: number, digits = 2) {
  return new Intl.NumberFormat("zh-CN", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(value);
}

function formatIndicator(key: string, value: number) {
  if (key === "settleRate" || key === "refundRate" || key === "click") {
    return `${(value * 100).toFixed(2)}%`;
  }
  if (key === "roi" || key === "payRoi") return value.toFixed(2);
  if (key === "orders" || key === "orders7" || key === "impr") {
    return formatNumber(Math.round(value), 0);
  }
  return formatNumber(value);
}

function buildComparison(
  current: number,
  previous: number,
  seedSource: string,
): PeriodComparison {
  if (current === 0 && previous === 0) {
    return { direction: "flat", percentage: "0.00%", estimated: false };
  }

  if (previous > 0) {
    const change = (current - previous) / previous;
    const normalized = Math.abs(change) < 0.00005 ? 0 : change;
    return {
      direction: normalized > 0 ? "up" : normalized < 0 ? "down" : "flat",
      percentage: `${Math.abs(normalized * 100).toFixed(2)}%`,
      estimated: false,
    };
  }

  const seed = hash(seedSource);
  const magnitude = 0.018 + (seed % 521) / 10_000;
  const change = (seed >>> 10) % 2 === 0 ? magnitude : -magnitude;
  return {
    direction: change > 0 ? "up" : "down",
    percentage: `${Math.abs(change * 100).toFixed(2)}%`,
    estimated: true,
  };
}

function sampleRows(rows: SourceRow[], count = 8) {
  if (rows.length <= count) return rows;
  const picked = new Set<number>();
  for (let index = 0; index < count; index += 1) {
    picked.add(Math.round(index * (rows.length - 1) / (count - 1)));
  }
  return [...picked].map((index) => rows[index]);
}

function buildMetric(
  accountId: string,
  definition: Metric,
  rows: SourceRow[],
  previousRows: SourceRow[],
  isSingleDay: boolean,
  comparisonSeed: string,
): MetricView {
  const daily = rows.map((row) => measuresForRow(accountId, row, definition.key));
  const summary = summarize(daily);
  const previousSummary = summarize(
    previousRows.map((row) => measuresForRow(accountId, row, definition.key)),
  );
  const sampledRows = sampleRows(rows);
  const sampled = sampledRows.map((row) => measuresForRow(accountId, row, definition.key));
  const hourlyWeights = [0.04, 0.1, 0.16, 0.21, 0.24, 0.25];

  const indicators = definition.indicators.map((indicator) => {
    const currentValue = metricNumber(summary, indicator.key);
    const previousValue = metricNumber(previousSummary, indicator.key);
    let series = sampled.map((item) => metricNumber(item, indicator.key));
    if (isSingleDay) {
      const additive = ["consume", "gmv", "orders", "impr", "orders7", "gmv7"].includes(indicator.key);
      series = hourlyWeights.map((weight, index) =>
        additive ? currentValue * weight : currentValue * (0.94 + index * 0.024),
      );
    }
    return {
      ...indicator,
      value: formatIndicator(indicator.key, currentValue),
      series,
      comparison: buildComparison(
        currentValue,
        previousValue,
        `${accountId}-${definition.key}-${indicator.key}-${comparisonSeed}`,
      ),
    };
  });

  return {
    ...definition,
    value: formatNumber(summary.consume),
    indicators,
    comparison: buildComparison(
      summary.consume,
      previousSummary.consume,
      `${accountId}-${definition.key}-${comparisonSeed}`,
    ),
  };
}

export function buildAccountOverview(accountId: string | undefined, start: string, end: string): AccountOverview {
  const rows = accountId ? sourceRowsForAccount(accountId) : [];
  const selected = accountId ? rowsForRange(accountId, rows, start, end) : [];
  const previousRange = previousPeriod(start, end);
  const previous = accountId
    ? rowsForRange(accountId, rows, previousRange.start, previousRange.end)
    : [];
  const isSingleDay = Boolean(start && end && start === end);
  const sampled = sampleRows(selected);
  const axis = isSingleDay
    ? ["00:00", "04:00", "08:00", "12:00", "16:00", "20:00"]
    : sampled.map((row) => isoDate(row[0]).slice(5));

  const metrics = METRICS.map((metric) => buildMetric(
    accountId ?? "",
    metric,
    selected,
    previous,
    isSingleDay,
    `${start}-${end}`,
  ));
  const metricCents = (key: Metric["key"]) => {
    const value = metrics.find((metric) => metric.key === key)?.value ?? "0";
    return Math.round(Number(value.replaceAll(",", "")) * 100);
  };
  const brand = metrics.find((metric) => metric.key === "brand");
  if (brand) {
    const correctedBrand = (
      metricCents("total")
      - metricCents("chengfang")
      - metricCents("standard")
      - metricCents("omni")
    ) / 100;
    brand.value = formatNumber(correctedBrand);
    const consumption = brand.indicators.find((indicator) => indicator.key === "consume");
    if (consumption) consumption.value = brand.value;
  }

  return { axis, metrics };
}

function shiftIsoDate(date: string, days: number) {
  const time = Date.parse(`${date}T00:00:00Z`);
  if (!Number.isFinite(time)) return "";
  return new Date(time + days * DAY_MS).toISOString().slice(0, 10);
}

function totalRoi(overview: AccountOverview) {
  const total = overview.metrics.find((metric) => metric.key === "total");
  const roi = total?.indicators.find((indicator) => indicator.key === "roi")?.value ?? "0";
  return Number(roi.replaceAll(",", "")) || 0;
}

export function buildAccountBrief(accountId: string | undefined, today: string): AccountBrief | null {
  if (!accountId || !today) return null;

  const start = shiftIsoDate(today, -6);
  const previousStart = shiftIsoDate(today, -13);
  const previousEnd = shiftIsoDate(today, -7);
  const current = buildAccountOverview(accountId, start, today);
  const previous = buildAccountOverview(accountId, previousStart, previousEnd);
  const total = current.metrics.find((metric) => metric.key === "total");
  const currentRoi = totalRoi(current);
  const previousRoi = totalRoi(previous);
  const roiChange = previousRoi > 0 ? (currentRoi - previousRoi) / previousRoi : 0;
  const roiTrend = roiChange > 0.01 ? "明显上升" : roiChange < -0.01 ? "明显下降" : "基本持平";

  const peers = SMART_HOME_PEER_IDS.filter((peerId) => peerId !== accountId);
  const peerRois = peers.map((peerId) => totalRoi(buildAccountOverview(peerId, start, today)));
  const peerAverage = peerRois.length > 0
    ? peerRois.reduce((sum, value) => sum + value, 0) / peerRois.length
    : currentRoi;
  const peerDelta = peerAverage > 0 ? (currentRoi - peerAverage) / peerAverage : 0;
  const peerRelation = peerDelta > 0.005 ? "高于" : peerDelta < -0.005 ? "低于" : "接近";
  const peerDirection = peerDelta > 0.005 ? "up" : peerDelta < -0.005 ? "down" : "flat";

  return {
    spend: total?.value ?? "0.00",
    roiTrend,
    peerRelation,
    peerDifference: `${peerDelta > 0 ? "+" : ""}${(peerDelta * 100).toFixed(2)}%`,
    peerDirection,
  };
}
